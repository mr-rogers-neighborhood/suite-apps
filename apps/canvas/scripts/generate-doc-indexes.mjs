#!/usr/bin/env node
/**
 * Generates the four section dashboards under `docs/`.
 *
 * Each index is a table of that section's pages, newest first. The date comes
 * from the file's last git commit, so a reader can tell which pages changed
 * recently without a second source of truth.
 *
 * A commit date does not exist until the commit does. While a page has
 * uncommitted changes, writing its row would record the previous commit, and the
 * commit that carries the page would make the table stale immediately. So the
 * generator refuses to write then, and the order is: commit the page, regenerate
 * the indexes, commit them. A `--check` on a tree with a pending page leaves
 * that one section unverified, with a note, because there is nothing truthful to
 * compare against yet.
 *
 *   node scripts/generate-doc-indexes.mjs            # rewrite the indexes
 *   node scripts/generate-doc-indexes.mjs --check    # exit 1 when stale
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const SECTIONS = [
  {
    dir: "tutorials",
    title: "Tutorials",
    intro:
      "Learn by doing. Each page is one guided path to a first success, with nothing to decide first.",
  },
  {
    dir: "how-to",
    title: "How-to",
    intro: "One task at a time: the steps for a job you already know you need to do.",
  },
  {
    dir: "reference",
    title: "Reference",
    intro: "Facts to look up: the data model, the commands, the quotas, the security boundary.",
  },
  {
    dir: "explanation",
    title: "Explanation",
    intro:
      "Why the product and the code are shaped this way, including the decisions that produced them.",
  },
];

const GENERATED = "<!-- generated by scripts/generate-doc-indexes.mjs; do not edit -->";

function repoPath(root, path) {
  return relative(root, path).split(sep).join("/");
}

/**
 * Whether this tree can answer "when was this page last committed".
 *
 * A source archive, a container export and a `git archive` all lack `.git`, and the index is a
 * table of *commit* dates. Falling back to the file's mtime there is worse than useless: an
 * export unpacks every file at the same second, so every date in the table becomes that second,
 * the rows re-sort alphabetically, and running the generator in that tree rewrites the real dates
 * to today's. That is how a documentation index quietly becomes wrong.
 *
 * So the date comes from git or not at all. Never from mtime.
 */
function hasGitHistory(root) {
  try {
    execFileSync("git", ["rev-parse", "--git-dir"], { cwd: root, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

/** The commit date of a page, or null when this tree cannot tell. */
function lastModified(root, path) {
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%cI", "--", repoPath(root, path)], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    if (out) return out;
  } catch {
    // An untracked page has no commit yet.
  }
  return null;
}

/**
 * Paths under this repository root with uncommitted changes or no commit yet,
 * relative to the root.
 *
 * `--relative` keeps `git diff` on a checkout whose repository root is above
 * this one (the Suite monorepo) reporting the same shape as `ls-files`.
 */
function uncommittedPaths(root) {
  const paths = new Set();
  for (const args of [
    ["diff", "--name-only", "--relative", "HEAD"],
    ["ls-files", "--others", "--exclude-standard"],
  ]) {
    let out = "";
    try {
      out = execFileSync("git", args, {
        cwd: root,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
    } catch {
      // No HEAD yet, or not a repository: every page reads as untracked below.
      continue;
    }
    for (const line of out.split("\n")) {
      const path = line.trim();
      if (path) paths.add(path);
    }
  }
  return paths;
}

function titleAndSummary(path) {
  const raw = readFileSync(path, "utf8").replace(/<!--[\s\S]*?-->/g, "");
  const lines = raw.split("\n");
  const heading = lines.find((line) => line.startsWith("# "));
  const title = heading ? heading.slice(2).trim() : repoPath(path).replace(/\.md$/, "");
  let start = heading ? lines.indexOf(heading) + 1 : 0;
  if (/^ADR-/.test(title)) {
    const decision = lines.findIndex(
      (line, index) => index > start && line.trim() === "## Decision",
    );
    if (decision !== -1) start = decision + 1;
  }
  let paragraph = "";
  let fenced = false;
  let inList = false;
  for (const line of lines.slice(start)) {
    if (/^\s*(```|~~~)/.test(line)) {
      fenced = !fenced;
      continue;
    }
    if (fenced) continue;
    const trimmed = line.trim();
    if (trimmed === "") {
      if (paragraph) break;
      inList = false;
      continue;
    }
    if (/^(\||#|>)/.test(trimmed)) {
      if (paragraph) break;
      continue;
    }
    const listItem = /^(?:[-*] |\d+\. )(.+)$/.exec(trimmed);
    if (listItem) {
      if (inList && paragraph) break;
      paragraph = listItem[1];
      inList = true;
      continue;
    }
    if (inList) break;
    paragraph = paragraph ? `${paragraph} ${trimmed}` : trimmed;
  }
  const summary = paragraph
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[`*]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return { title, summary: summary.length > 150 ? `${summary.slice(0, 150).trimEnd()}…` : summary };
}

function pagesIn(root, section) {
  const base = join(root, "docs", section.dir);
  if (!existsSync(base)) return [];
  const pages = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith(".") || entry.name === "index.md") continue;
      if (entry.name === "README.md" || entry.name === "TEMPLATE.md") continue;
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(path);
        continue;
      }
      if (!entry.name.endsWith(".md")) continue;
      const { title, summary } = titleAndSummary(path);
      const rel = relative(base, path).split(sep).join("/");
      pages.push({
        path,
        rel,
        title,
        summary,
        // Resolved before sorting: the committed index is ordered newest first, and a title
        // order would rewrite every row's position even when nothing about a page changed.
        date: lastModified(root, path) ?? "",
        group:
          section.dir === "explanation" && relative(base, path).startsWith("decisions")
            ? "Decisions"
            : section.dir === "explanation"
              ? "Direction"
              : null,
      });
    }
  };
  walk(base);
  // Newest first. With no dates to compare, title is the only stable order, and the committed
  // index is compared on content rather than reshuffled.
  return pages.sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title));
}

function table(pages) {
  const rows = pages.map(
    (page) =>
      `| [${page.title}](${page.rel}) | ${page.summary || "—"} | ${page.date.slice(0, 10)} |`,
  );
  return ["| Article | What it covers | Updated |", "| --- | --- | --- |", ...rows].join("\n");
}

function render(root, section) {
  const pages = pagesIn(root, section);
  const parts = [GENERATED, "", `# ${section.title}`, "", section.intro, ""];
  if (section.dir === "explanation") {
    for (const group of ["Direction", "Decisions"]) {
      const groupPages = pages.filter((page) => page.group === group);
      if (groupPages.length === 0) continue;
      parts.push(`## ${group}`, "", table(groupPages), "");
    }
  } else {
    parts.push(table(pages), "");
  }
  return `${parts.join("\n").trimEnd()}\n`;
}

/**
 * Regenerate every section index under `root`.
 *
 * Returns `{ refused, unverified, stale, wrote }`, each a list of paths. `refused`
 * is non-empty only when writing, and means nothing was written: those pages need
 * a commit before their dates exist. `unverified` is the check-mode counterpart,
 * a section left alone because a page in it has uncommitted changes.
 */
export function generateIndexes({ root, check = false, log = console }) {
  const result = { refused: [], unverified: [], stale: [], wrote: [] };
  if (!hasGitHistory(root)) {
    // A row's date is a commit date and the rows are ordered by its *time* within that day, which
    // the index does not store. Without history the table is neither verifiable nor regenerable, so
    // this says so rather than comparing against a guess.
    if (check) {
      log.log("doc indexes: skipped, this tree has no git history to date them from");
      return result;
    }
    throw new Error(
      "doc indexes cannot be written here: a row's date and order come from commit timestamps and " +
        "this tree has no .git. Run it in a checkout.",
    );
  }

  const uncommitted = uncommittedPaths(root);
  const sections = SECTIONS.map((section) => {
    const prefix = `docs/${section.dir}/`;
    return {
      section,
      pending: [...uncommitted]
        .filter((path) => path.startsWith(prefix) && path.endsWith(".md"))
        .filter((path) => path !== `${prefix}index.md`)
        .sort(),
    };
  });

  if (!check) {
    // All or nothing: a partial rewrite would leave the tree looking generated
    // while one section still carries a date the next commit invalidates.
    result.refused = sections.flatMap(({ pending }) => pending.map((path) => join(root, path)));
    if (result.refused.length > 0) return result;
  }

  for (const { section, pending } of sections) {
    if (pending.length > 0) {
      result.unverified.push(join(root, "docs", section.dir, "index.md"));
      continue;
    }

    const target = join(root, "docs", section.dir, "index.md");
    const next = render(root, section);
    const current = (() => {
      try {
        return readFileSync(target, "utf8");
      } catch {
        return "";
      }
    })();
    if (current === next) continue;
    if (check) {
      result.stale.push(target);
    } else {
      writeFileSync(target, next);
      result.wrote.push(target);
    }
  }
  return result;
}

function main(argv = process.argv.slice(2), log = console) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const check = argv.includes("--check");
  const result = generateIndexes({ root, check });
  const name = (path) => relative(root, path).split(sep).join("/");

  for (const path of result.unverified) {
    log.log(`doc indexes: left ${name(path)} unverified until its pages are committed`);
  }
  if (result.refused.length > 0) {
    for (const path of result.refused) log.error(`page with uncommitted changes: ${name(path)}`);
    log.error(
      `doc indexes cannot be written: ${result.refused.length} page(s) above have no commit yet, ` +
        "and a row's date is the date of that commit. Commit the pages, run this again, then " +
        "commit the indexes.",
    );
    return 1;
  }
  if (result.stale.length > 0) {
    for (const path of result.stale) log.error(`${name(path)} is out of date`);
    log.error(
      "run node scripts/generate-doc-indexes.mjs and commit the indexes: a page is dated by its " +
        "own commit, so an index always lands one commit after the page it dates.",
    );
    return 1;
  }
  for (const path of result.wrote) log.log(`wrote ${name(path)}`);
  return 0;
}

const invokedDirectly =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) process.exitCode = main();
