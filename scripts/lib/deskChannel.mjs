/**
 * Suite Desk's channel-specific Flatpak pieces.
 *
 * The identities in `channel.mjs` describe every app: stable keeps its id and
 * each pre-release channel has its own. Desk differs from a mini-app in two
 * ways that belong here, not in the shared identity:
 *
 * - it ships no `suite.app.json`, so there is no pre-release app manifest to
 *   generate, and
 * - its document and pack data live in its own sandbox data root rather than in
 *   `Documents/Suite`, so its pre-release keeps the stable sandbox grants and
 *   relies on the per-channel Flatpak id for a separate profile.
 *
 * The pure functions are exported so the desk channel test can prove the id,
 * branch, name, data root and generated manifest without running a build.
 */
import { flatpakId } from "./channel.mjs";

/** The Flatpak id whose sandbox holds this channel's Desk data. */
function deskSandboxHome(channel) {
  return `~/.var/app/${flatpakId("desk", channel)}`;
}

/**
 * The Desk data root inside its own Flatpak sandbox.
 *
 * Electron puts `userData` under `XDG_CONFIG_HOME`, and the app keeps its packs,
 * Space document and Screens under `<userData>/desk`. Flatpak gives each id its
 * own home, so every channel — stable included — has a different path. The
 * pre-release root is the host's equivalent of the mini-app `Documents/Suite
 * Slop` rule: the channel's id keeps its data apart from stable and from every
 * other channel, and a preview build cannot open slop data.
 *
 * This is a fresh root. An install of the old `run.suite.shell` id is ignored;
 * its `~/.var/app/run.suite.shell` data is not read, copied or renamed.
 */
export function deskDataRoot(channel) {
  return `${deskSandboxHome(channel)}/config/Suite Desk/desk`;
}

/**
 * Rewrite the stable Desk manifest for one pre-release channel.
 *
 * Everything the stable manifest decides — runtime, base, cleanup commands,
 * build commands, the asar patch and the narrow grants — is kept. Only the id
 * and the paths that name this build change:
 *
 * - `app-id` and `command` become the channel's id;
 * - the launcher, desktop entry, metainfo and every icon name follow the id;
 * - the unpacked tree is named absolutely because the generated manifest lives
 *   under `packaging/flatpak/.build/`, not beside `run.suite.desk.yml`;
 * - the generated desktop entry, metainfo, launcher and renamed icons sit in
 *   that same generated directory, so their `path:` entries stay relative.
 *
 * The pre-release keeps the stable `finish-args`: the host has no
 * `Documents/Suite` grant to split, and adding the mini-app `Suite Slop` folder
 * would widen a host that deliberately opens only through portals.
 */
export function deskPreReleaseManifest(
  stableManifest,
  { id, channel, stableId = "run.suite.desk", unpacked },
) {
  const rewritten = stableManifest
    .replace(/^app-id:.*$/mu, `app-id: ${id}`)
    .replace(/^command:.*$/mu, `command: ${id}`)
    .replace(/^(\s*)- name: suite-desk$/mu, `$1- name: suite-desk-${channel}`)
    .replace(
      /^(\s*)path: \.\.\/\.\.\/hosts\/desk\/release\/linux-unpacked$/mu,
      `$1path: ${unpacked}`,
    )
    .replaceAll(stableId, id);

  return [
    `# Generated by scripts/flatpak.mjs --app desk --channel ${channel}.`,
    "# The stable manifest is the source of the runtime, build steps and grants.",
    "",
    rewritten.trimEnd(),
    "",
  ].join("\n");
}
